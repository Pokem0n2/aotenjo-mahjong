import { getPatternName } from './engine/shanten-new';

// 正确的九莲宝灯: 1112345678999s + 1s
// 条子索引: 18=1s, 19=2s, 20=3s, 21=4s, 22=5s, 23=6s, 24=7s, 25=8s, 26=9s
// 九莲宝灯结构: 1s×3, 2s×1, 3s×1, 4s×1, 5s×1, 6s×1, 7s×1, 8s×1, 9s×2 = 12张? 不对
// 应该是14张: 1s×3(刻子) + 2s×1 + 3s×1 + 4s×1 + 5s×1 + 6s×1 + 7s×1 + 8s×1 + 9s×2(雀头) = 12张
// 九莲宝灯需要4个面子+1个雀头 = 14张
// 1s×3(刻子) + 2s-3s-4s(顺子) + 5s-6s-7s(顺子) + 8s-9s-?(需要8s×1,9s×1,但还需要一张)
// 正确的九莲宝灯: 
// 1s×1, 2s×1, 3s×1, 4s×1, 5s×1, 6s×1, 7s×1, 8s×1, 9s×1 (9张)
// + 1s×1, 2s×1, 3s×1, 4s×1, 5s×1 (再加5张组成面子) = 14张
// 实际上: 1s×3, 2s×3, 3s×3, 4s×2, 5s×1, 6s×1, 7s×1, 8s×1, 9s×1 = 不是九莲宝灯

// 让我用正确的九莲宝灯结构:
// 1112345678999 + 任意一张同花色
// 即: 1s×3, 2s×1, 3s×1, 4s×1, 5s×1, 6s×1, 7s×1, 8s×1, 9s×2 = 12张...还是不对

// 等等，让我重新理解:
// 九莲宝灯 = 1112345678999(13张) + 任意一张同花色(1张) = 14张
// 但1112345678999本身是13张: 1×3, 2×1, 3×1, 4×1, 5×1, 6×1, 7×1, 8×1, 9×2 = 12张?
// 1+1+1+1+1+1+1+1+1 = 9张? 不对

// 1112345678999:
// 1出现3次, 2出现1次, 3出现1次, 4出现1次, 5出现1次, 6出现1次, 7出现1次, 8出现1次, 9出现2次
// 3+1+1+1+1+1+1+1+2 = 12张

// 实际上九莲宝灯应该是13张听牌，14张和牌
// 听牌时: 1112345678999 = 12张? 不对
// 标准定义: 1112345678999 = 1×3 + 2×1 + 3×1 + 4×1 + 5×1 + 6×1 + 7×1 + 8×1 + 9×2 = 12张
// 但应该是13张听牌...

// 可能我理解错了。让我查一下:
// 九莲宝灯听牌: 1112345678999 = 13张
// 即: 1×2, 2×1, 3×1, 4×1, 5×1, 6×1, 7×1, 8×1, 9×2 = 11张? 
// 还是: 1×3, 2×1, 3×1, 4×1, 5×1, 6×1, 7×1, 8×1, 9×2 = 12张

// 我认为正确的理解是:
// 九莲宝灯 = 同一种花色的 1112345678999 + 任意一张
// 其中 1112345678999 表示该花色的9种牌各至少1张
// 总张数 = 14张（和牌）

// 让我用简单的方式测试: 9种牌各至少1张，总共14张，且能胡牌
const nineLantern = new Array(34).fill(0);
// 条子: 1s到9s各至少1张
for (let i = 18; i <= 26; i++) {
  nineLantern[i] = 1;
}
// 再加5张组成4面子+1雀头
// 例如: 1s×2(雀头), 2s×3(刻子), 3s×3(刻子) 
// 但这样1s有3张, 2s有4张, 3s有4张...
nineLantern[18] = 3; // 1s×3 (刻子)
nineLantern[19] = 3; // 2s×3 (刻子)
nineLantern[20] = 3; // 3s×3 (刻子)
nineLantern[21] = 3; // 4s×3 (刻子)
nineLantern[22] = 2; // 5s×2 (雀头)
// 但这样就不是"9种牌各至少1张"了，因为6s-9s只有1张

// 让我重新设置:
// 1s×3, 2s×3, 3s×3, 4s×2, 5s×1, 6s×1, 7s×1, 8s×1, 9s×1 = 16张 太多

// 正确的九莲宝灯应该是:
// 1s×2, 2s×1, 3s×1, 4s×1, 5s×1, 6s×1, 7s×1, 8s×1, 9s×2 = 11张? 不对

// 让我直接测试一个已知的和牌型:
// 4个顺子 + 1个雀头 = 14张
// 顺子1: 1-2-3s, 顺子2: 4-5-6s, 顺子3: 7-8-9s, 顺子4: 1-2-3s, 雀头: 1s
// 1s×4, 2s×2, 3s×2, 4s×1, 5s×1, 6s×1, 7s×1, 8s×1, 9s×1 = 14张
const testHand = new Array(34).fill(0);
testHand[18] = 4; // 1s
testHand[19] = 2; // 2s
testHand[20] = 2; // 3s
testHand[21] = 1; // 4s
testHand[22] = 1; // 5s
testHand[23] = 1; // 6s
testHand[24] = 1; // 7s
testHand[25] = 1; // 8s
testHand[26] = 1; // 9s
const total = testHand.reduce((a, b) => a + b, 0);
console.log('测试手牌总张数:', total);
console.log('测试手牌牌型:', getPatternName(testHand));

// 这个不是九莲宝灯，因为9种牌不是各至少1张（只是恰好都是1张或以上）
// 九莲宝灯的关键是: 1112345678999 结构，即1和9有3张(或2张)，其他各1张

// 让我试: 1s×3, 2s×1, 3s×1, 4s×1, 5s×1, 6s×1, 7s×1, 8s×1, 9s×3 = 14张
const nineLantern2 = new Array(34).fill(0);
nineLantern2[18] = 3; // 1s×3
nineLantern2[19] = 1; // 2s
nineLantern2[20] = 1; // 3s
nineLantern2[21] = 1; // 4s
nineLantern2[22] = 1; // 5s
nineLantern2[23] = 1; // 6s
nineLantern2[24] = 1; // 7s
nineLantern2[25] = 1; // 8s
nineLantern2[26] = 3; // 9s×3
const total2 = nineLantern2.reduce((a, b) => a + b, 0);
console.log('\n九莲宝灯总张数:', total2);
console.log('九莲宝灯牌型:', getPatternName(nineLantern2));
