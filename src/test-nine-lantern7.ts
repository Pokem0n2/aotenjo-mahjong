import { getPatternName } from './engine/shanten-new';

// 正确的九莲宝灯: 14张
// 九莲宝灯 = 1112345678999 + 任意一张同花色
// 即: 1s×3, 2s×1, 3s×1, 4s×1, 5s×1, 6s×1, 7s×1, 8s×1, 9s×2 = 12张（基础）
// + 任意一张同花色 = 13张? 还是14张?

// 让我重新理解: 
// 1112345678999 中:
// 1出现3次, 2出现1次, 3出现1次, 4出现1次, 5出现1次, 6出现1次, 7出现1次, 8出现1次, 9出现2次
// 3+1+1+1+1+1+1+1+2 = 12张

// 但九莲宝灯应该是13张听牌，14张和牌
// 听牌时: 1112345678999 = 12张? 不对
// 标准定义中，九莲宝灯听牌是13张: 
// 1×2, 2×1, 3×1, 4×1, 5×1, 6×1, 7×1, 8×1, 9×2 = 11张? 

// 实际上: 九莲宝灯听牌型是13张牌
// 1112345678999 = 1×3 + 2×1 + 3×1 + 4×1 + 5×1 + 6×1 + 7×1 + 8×1 + 9×2 = 12张
// 但和牌需要14张...

// 可能我对九莲宝灯的理解有误。让我用另一种方式:
// 九莲宝灯 = 4个顺子(1-2-3, 4-5-6, 7-8-9, 1-2-3) + 雀头(1) = 14张
// 但这需要1s×4, 2s×2, 3s×2, 4s×1, 5s×1, 6s×1, 7s×1, 8s×1, 9s×1 = 14张
// 这不是"9种牌各至少1张"，因为9s只有1张

// 另一种理解:
// 九莲宝灯 = 3个刻子(1-1-1, 9-9-9) + 2个顺子(2-3-4, 5-6-7) + 雀头(8) = 14张
// 1s×3, 2s×1, 3s×1, 4s×1, 5s×1, 6s×1, 7s×1, 8s×2, 9s×3 = 14张
// 这个满足: 9种牌各至少1张, 1和9有3张(≥2), 总共14张
const nineLantern = new Array(34).fill(0);
nineLantern[18] = 3; // 1s×3
nineLantern[19] = 1; // 2s
nineLantern[20] = 1; // 3s
nineLantern[21] = 1; // 4s
nineLantern[22] = 1; // 5s
nineLantern[23] = 1; // 6s
nineLantern[24] = 1; // 7s
nineLantern[25] = 2; // 8s×2 (雀头)
nineLantern[26] = 3; // 9s×3
const total = nineLantern.reduce((a, b) => a + b, 0);
console.log('九莲宝灯总张数:', total);
console.log('九莲宝灯牌型:', getPatternName(nineLantern));

// 普通清一色（不是九莲宝灯）
// 1s×4, 2s×2, 3s×2, 4s×2, 5s×2, 6s×2 = 14张
const pure = new Array(34).fill(0);
pure[18] = 4;
pure[19] = 2;
pure[20] = 2;
pure[21] = 2;
pure[22] = 2;
pure[23] = 2;
const total2 = pure.reduce((a, b) => a + b, 0);
console.log('\n普通清一色总张数:', total2);
console.log('普通清一色牌型:', getPatternName(pure));
